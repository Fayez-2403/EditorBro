"""Lay the narration lines on the beat grid and write SCENE_TIMINGS.json, the single timing source for the compositions,
the captions and the sound cue sheet, plus public/audio/vo_<variant>.wav (the narration on the film's timeline).

Each line opens its scene. A scene lasts max(its min, lead + line + tail), rounded up to the grid (master: one beat,
reel: half a beat), so a long line lengthens its scene instead of being cramped. A line's "cut" starts another scene at
one of its phrases (the reel's Highspeed beat). Re-run after vo.py, scratch_vo.py or align.py.

    python scripts/audio/timing.py            # both cuts
"""
import json, math, pathlib, sys

import numpy as np
import soundfile as sf

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
import sys as _s
_s.path.insert(0, str(HERE))
from version import V, SUFFIX, OUT as VOUT, TIMINGS  # noqa: E402
from version import SCRIPT_PATH as _SP  # noqa: E402
FPS = 60
BPM = float(__import__('json').loads(_SP.read_text(encoding='utf-8')).get('bpm', 120))   # voScript.json "bpm": the score's tempo (a song's MEASURED bpm, never a guess)
BEAT = 60 / BPM
SR = 44100
CFG = {
    "reel": {"w": 1080, "h": 1920, "grid": BEAT / 2, "lead": 0.1, "hookLead": 0.05, "tail": 0.12, "endHold": 0.5, "total": None},
}


def up(t, g): return math.ceil(t / g - 1e-6) * g
def near(t, g): return round(t / g) * g
def fr(t): return int(round(t * FPS))


def captions(lines_abs):
    """merge a line's phrases into caption cards of 3-7 words (never across lines)."""
    out = []
    for start, l in lines_abs:
        card = None
        for p in l["phrases"]:
            n = len(p["cap"].split())
            if card and len(card["text"].split()) + n <= 7 and (len(card["text"].split()) < 3 or n < 3):
                card["text"] += " " + p["cap"]; card["t1"] = round(start + p["t1"], 3)
                card["words"] += [{**w, "t0": round(start + w["t0"], 3), "t1": round(start + w["t1"], 3)} for w in p["words"]]
            else:
                if card: out.append(card)
                card = {"line": l["id"], "t0": round(start + p["t0"], 3), "t1": round(start + p["t1"], 3), "text": p["cap"],
                        "words": [{**w, "t0": round(start + w["t0"], 3), "t1": round(start + w["t1"], 3)} for w in p["words"]]}
        out.append(card)
    return out


def build(variant):
    c = CFG[variant]
    meta = json.loads((VOUT / f"lines_{variant}.json").read_text(encoding="utf-8"))
    t, scenes, vo, placed = 0.0, [], [], []
    for i, l in enumerate(meta["lines"]):
        lead = (c["hookLead"] if i == 0 else c["lead"]) + l.get("pre", 0)   # "pre": a designed silence before the line
        last = i == len(meta["lines"]) - 1
        dur = up(max(l["min"], lead + l["dur"] + (c["endHold"] if last else c["tail"])), c["grid"])
        if last and c.get("total"): dur = max(dur, c["total"] - t)          # pad the end card to the exact film length
        s0 = t + lead
        if l.get("cut"):
            p = l["phrases"][l["cut"]["phrase"]]
            tc = near(s0 + p["t0"] - 0.2, c["grid"])
            scenes.append({"id": l["scene"], "start": t, "end": tc}); scenes.append({"id": l["cut"]["scene"], "start": tc, "end": t + dur})
        else:
            scenes.append({"id": l["scene"], "start": t, "end": t + dur})
        vo.append({"id": l["id"], "scene": l["scene"], "start": round(s0, 3), "end": round(s0 + l["dur"], 3)})
        placed.append((s0, l)); t += dur
    total = t
    for s in scenes:
        s["from"], s["durationInFrames"] = fr(s["start"]), fr(s["end"]) - fr(s["start"])
        s["start"], s["end"] = round(s["start"], 3), round(s["end"], 3)
    # narration on the timeline
    y = np.zeros(int(total * SR) + SR, np.float32)
    for v, (s0, l) in zip(vo, placed):
        a, sr = sf.read(VOUT / variant / f"{l['id']}.wav", dtype="float32")
        assert sr == SR
        k = int(s0 * SR); y[k:k + len(a)] += a[: len(y) - k]
    y = y[: int(total * SR)]
    (ROOT / "public" / "audio").mkdir(parents=True, exist_ok=True)
    sf.write(ROOT / "public" / "audio" / f"vo_{variant}{SUFFIX}.wav", y, SR, subtype="PCM_16")
    return {"width": c["w"], "height": c["h"], "durationInFrames": fr(total), "seconds": round(total, 3),
            "voSource": meta["source"], "scratch": meta["scratch"], "scenes": scenes, "vo": vo, "captions": captions(placed)}


def main():
    out = {"_doc": "Generated by scripts/audio/timing.py from the narration timings. Do not edit by hand.",
           "fps": FPS, "bpm": BPM, "beat": BEAT, "variants": {}}
    for v in ("reel",):
        if (VOUT / f"lines_{v}.json").exists():
            out["variants"][v] = build(v)
            r = out["variants"][v]
            print(f"{v}: {r['seconds']:.2f} s, {r['durationInFrames']} frames, {len(r['scenes'])} scenes, {len(r['captions'])} caption cards"
                  + ("  [SCRATCH VO]" if r["scratch"] else ""))
            for s in r["scenes"]: print(f"   {s['id']:<11} {s['start']:7.2f} - {s['end']:7.2f}  ({s['end'] - s['start']:.2f} s)")
    out["version"] = V
    TIMINGS.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print("wrote", TIMINGS.name, "- make it active with: src/config/version.ts ->", V)


if __name__ == "__main__":
    main()
